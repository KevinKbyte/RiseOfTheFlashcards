// Build-time precache service worker for premise g (offline reload). Runs in Node during
// `vite build`; the emitted sw.js is plain JS with the list and cache name baked in.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import type { Plugin } from 'vite';

const CACHE_PREFIX = 'probe-precache-';
const SW_FILE = 'sw.js';

export function buildPrecacheList(relPaths: string[]): string[] {
  const kept = new Set<string>();
  for (const raw of relPaths) {
    const p = raw.replace(/\\/g, '/').replace(/^\.\//, '');
    if (p === '' || p === SW_FILE || p.endsWith('.map')) continue;
    kept.add(`./${p}`);
  }
  return ['./', ...[...kept].sort()];
}

// The digest covers file bytes so a same-named rebuild with changed content still gets a new cache.
export function cacheNameFor(list: string[], contentDigest?: string): string {
  const h = createHash('sha256').update(JSON.stringify(list));
  if (contentDigest !== undefined) h.update(`\n${contentDigest}`);
  return CACHE_PREFIX + h.digest('hex').slice(0, 16);
}

export function renderServiceWorker(list: string[], contentDigest?: string): string {
  return `// Generated by vite-plugins/sw-precache.ts -- do not edit.
const PRECACHE = ${JSON.stringify(list)};
const CACHE = ${JSON.stringify(cacheNameFor(list, contentDigest))};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const scoped = (p) => new URL(p, self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map(scoped)))
      .then(() => self.skipWaiting()),
  );
});

// Only our own stale caches are dropped; foreign caches (e.g. transformers.js model cache) stay.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;
  // Navigations ignore the query string so ./?x=1 is served from the cached ./ offline.
  const isNav = request.mode === 'navigate';
  event.respondWith(
    caches.match(request, isNav ? { ignoreSearch: true } : undefined).then(
      (hit) =>
        hit ||
        fetch(request).catch((err) => {
          if (request.mode !== 'navigate') throw err;
          return caches.match(scoped('index.html')).then((page) => {
            if (page) return page;
            throw err;
          });
        }),
    ),
  );
});
`;
}

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

export function swPrecache(): Plugin {
  let outDir = '';
  return {
    name: 'sw-precache',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    async closeBundle() {
      const files = (await walk(outDir)).map((f) => relative(outDir, f));
      const list = buildPrecacheList(files);
      // Hash in sorted list order (skipping the './' root alias) so the digest is deterministic.
      const digest = createHash('sha256');
      for (const p of list) {
        if (p === './') continue;
        digest.update(p).update('\0').update(await readFile(join(outDir, p))).update('\0');
      }
      await writeFile(join(outDir, SW_FILE), renderServiceWorker(list, digest.digest('hex')));
    },
  };
}
